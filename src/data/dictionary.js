// Helper to pick random secret word without repeating recent words
export function getRandomSecretWord(categoryId, recentWordsList = []) {
  let pool = WORD_DATABASE[categoryId];
  if (!pool || pool.length === 0) {
    pool = WORD_DATABASE.random;
  }

  const unusedPool = pool.filter(item => !recentWordsList.includes(item.word));
  const candidatePool = unusedPool.length > 0 ? unusedPool : pool;

  const randomIndex = Math.floor(Math.random() * candidatePool.length);
  const selected = candidatePool[randomIndex];

  let distractors = [...selected.distractors];

  if (distractors.length < 3) {
    const extraOptions = pool
      .map(i => i.word)
      .filter(w => w !== selected.word && !distractors.includes(w));
    while (distractors.length < 3 && extraOptions.length > 0) {
      const randExtra = extraOptions.splice(Math.floor(Math.random() * extraOptions.length), 1)[0];
      distractors.push(randExtra);
    }
  }

  const choices = [selected.word, ...distractors.slice(0, 3)].sort(() => Math.random() - 0.5);

  return {
    secretWord: selected.word,
    choices,
    categoryId
  };
}
