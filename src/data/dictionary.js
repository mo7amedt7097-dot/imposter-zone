function buildCategoryDataset(rawList) {
  return rawList.map((wordItem, idx) => {
    // Generate 3 distractors from within the same list
    const distractors = [];
    while (distractors.length < 3) {
      const randIdx = Math.floor(Math.random() * rawList.length);
      const candidate = rawList[randIdx];
      if (candidate !== wordItem && !distractors.includes(candidate)) {
        distractors.push(candidate);
      }
    }
    return {
      word: wordItem,
      distractors
    };
  });
}

